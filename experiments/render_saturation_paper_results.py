"""Render audited saturation evidence into a wide table and readable triptychs.

Run only after the controlled timing owner confirms the local CPU is free.
This presentation converter verifies every input receipt and reruns the
independent evidence auditor before using any stored statistic. It never
imports the benchmark driver or changes the paper's prose or abstract.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import importlib.util
import json
import math
from pathlib import Path
import tempfile

ROOT = Path(__file__).resolve().parents[1]
AUDITOR = ROOT / "experiments/summarize_saturation_evidence.py"
DEFAULT_EVIDENCE = ROOT / "artifacts/saturation/evidence-review/evidence.json"
STUDIES = (
    ("Mac-development", "Mac development"),
    ("Mac-external", "Mac external"),
    ("Linux-external", "Linux external"),
)
WIDTHS = (30, 100, 300)
CONTROLS = (
    ("active_full", "Full active scan"),
    ("last_positive", "Last-positive stop"),
    ("radix", "Released radix"),
    ("dense_radix", "Dense nearest radix"),
    ("klein", "fast-VUS"),
    ("sparse_comparison", "Sparse comparison sort"),
    ("dense_direct", "Dense direct"),
    ("dense_direct_radix", "Dense direct radix"),
    ("fastest_eight_control_oracle", "Fastest eight-control oracle"),
)
COLORS = {30: "#0072B2", 100: "#D55E00", 300: "#009E73"}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def source_path(study):
    """Retain absolute paths when present; support a relocated repository checkout."""
    recorded = Path(study["path"])
    if recorded.is_dir():
        return recorded.resolve()
    parts = recorded.parts
    require("artifacts" in parts, f"Cannot relocate study: {recorded}")
    relative = Path(*parts[parts.index("artifacts"):])
    candidate = (ROOT / relative).resolve()
    require(candidate.is_relative_to(ROOT) and candidate.is_dir(), f"Missing study: {recorded}")
    return candidate


def validate_receipts(evidence, auditor):
    checked = {}
    for study in evidence["studies"]:
        path = source_path(study)
        require(set(study["receipt_sha256"]) == set(auditor.RECEIPTS), "Unexpected receipt coverage")
        actual = {name: sha(path / name) for name in auditor.RECEIPTS}
        require(actual == study["receipt_sha256"], f"Receipt changed: {study['label']}")
        checked[study["label"]] = {"directory": str(path), "receipt_sha256": actual}
    return checked


def checked_evidence(path):
    # Import only the checked independent auditor; plotting imports remain deferred.
    initial_hash = sha(path)
    preliminary = json.loads(path.read_text())
    require(preliminary["auditor_sha256"] == sha(AUDITOR), "Auditor changed since the evidence was generated")
    spec = importlib.util.spec_from_file_location("saturation_publication_auditor", AUDITOR)
    auditor = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(auditor)
    evidence = auditor.load_json(path)
    require(evidence["schema_version"] == 1, "Unsupported evidence schema")
    labels = [study["label"] for study in evidence["studies"]]
    require(len(labels) == len(set(labels)) == 3 and set(labels) == {name for name, _ in STUDIES},
            "Expected exactly the three audited Mac-development/Mac-external/Linux-external studies")
    receipts = validate_receipts(evidence, auditor)
    indexed = {study["label"]: study for study in evidence["studies"]}
    for label, _ in STUDIES:
        stored = indexed[label]
        require(stored["audit_status"] == "PASS_RECORDED_EVIDENCE", f"Study was not audited: {label}")
        fresh = auditor.audit_study(label, source_path(stored))
        # Paths may change when the entire checkout moves; no numerical or identity field may change.
        comparable = dict(stored, path=fresh["path"])
        require(fresh == comparable, f"Stored evidence differs from independent reconstruction: {label}")
    require(sha(path) == initial_hash, "Evidence changed during validation")
    return [indexed[label] for label, _ in STUDIES], evidence, auditor, receipts, initial_hash


def table_text(studies, evidence_sha, renderer_sha, auditor_sha):
    lines = [
        "% Generated by experiments/render_saturation_paper_results.py; do not edit data by hand.",
        f"% Evidence SHA256: {evidence_sha}",
        f"% Renderer SHA256: {renderer_sha}",
        f"% Independent auditor SHA256: {auditor_sha}",
        r"\begin{table*}[t]", r"\centering", r"\footnotesize",
        r"\setlength{\tabcolsep}{2.5pt}", r"\renewcommand{\arraystretch}{1.10}",
        r"\begin{tabular}{l*{9}{r}}", r"\toprule",
        " & " + " & ".join(r"\multicolumn{3}{c}{" + title + "}" for _, title in STUDIES) + r" \\",
        r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}",
        "Control & " + " & ".join(f"$L={width}$" for _ in studies for width in WIDTHS) + r" \\",
        r"\midrule",
    ]
    for method, title in CONTROLS:
        if method == "fastest_eight_control_oracle":
            lines.append(r"\midrule")
        cells = []
        for study in studies:
            for width in WIDTHS:
                part = study["widths"][str(width)]
                value = part[method] if method == "fastest_eight_control_oracle" else part["comparisons"][method]
                require(value["wins"] + value["losses"] + value["ties"] == part["cases"], "Invalid summary counts")
                cells.append(f"{value['median_ratio']:.3f}({value['losses']})")
        lines.append(title + " & " + " & ".join(cells) + r" \\")
    counts = []
    decisions = []
    for (_, title), study in zip(STUDIES, studies):
        per_width = {study["widths"][str(width)]["cases"] for width in WIDTHS}
        require(len(per_width) == 1, "Table caption requires equal case counts at each width")
        counts.append(f"{title}: {per_width.pop()}")
        decisions.append(f"{title}: {'PASS' if study['primary_decision'] else 'FAIL'}")
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\caption{Median paired runtime ratio (control divided by saturation), with the number of slower saturation cases in parentheses. "
              + "Cases per width: " + "; ".join(counts) + ". "
              + r"A ratio below one favors the control. Each case uses the median of three complete public-call timings. "
              + r"The oracle selects the fastest of the eight measured controls separately for each case, after measurement. "
              + r"All cases and widths are retained. Frozen primary $L=30$ criterion: "
              + "; ".join(decisions) + ".}",
              r"\label{tab:saturation-all-controls}", r"\end{table*}", ""]
    return "\n".join(lines)


def figures(studies, directory):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.ticker import FuncFormatter, LogLocator, NullFormatter

    def log_ticks(axis, coordinate):
        which = axis.xaxis if coordinate == "x" else axis.yaxis
        which.set_major_locator(LogLocator(base=10, subs=(1., 2., 5.), numticks=8))
        which.set_major_formatter(FuncFormatter(lambda value, _position: f"{value:g}"))
        which.set_minor_formatter(NullFormatter())

    style = {"font.family": "DejaVu Sans", "font.size": 8.5, "axes.titlesize": 9,
             "axes.labelsize": 8.5, "xtick.labelsize": 8, "ytick.labelsize": 8,
             "legend.fontsize": 8, "pdf.fonttype": 42, "svg.fonttype": "none",
             "axes.linewidth": .65, "lines.linewidth": 1.15}
    outputs, plotted = [], {}
    with plt.rc_context(style):
        for kind in ("cdf", "work"):
            figure, axes = plt.subplots(1, 3, figsize=(7.2, 2.6))
            figure.subplots_adjust(left=.085, right=.987, bottom=.235, top=.865, wspace=.34)
            plotted[kind] = {}
            for index, (axis, study, (_, title)) in enumerate(zip(axes, studies, STUDIES)):
                all_ratios, all_work = [], []
                panel_counts = {}
                for width in WIDTHS:
                    rows = [row for row in study["case_results"] if row["max_buffer"] == width]
                    require(len(rows) == study["widths"][str(width)]["cases"], "Plot case coverage differs")
                    if kind == "cdf":
                        ratios = [row["fastest_control_ratio"] for row in rows]
                        summary = study["widths"][str(width)]["fastest_eight_control_oracle"]
                    else:
                        ratios = [row["control_ratios"]["active_full"] for row in rows]
                        summary = study["widths"][str(width)]["comparisons"]["active_full"]
                        require(all(ratio == row["median_seconds"]["active_full"] / row["median_seconds"]["saturation"]
                                    for row, ratio in zip(rows, ratios)), "Active-full runtime ratio differs")
                    work = [row["work_ratios"]["active_full"] for row in rows]
                    require(all(math.isfinite(value) and value > 0 for value in [*ratios, *work]), "Invalid plot data")
                    losses = sum(value < 1 for value in ratios)
                    require(losses == summary["losses"],
                            "Plot loss count differs from checked summary")
                    label = f"L={width}: {losses}/{len(rows)}"
                    if kind == "cdf":
                        ordered = sorted(ratios)
                        # Include the zero-height endpoint, then the jump for every case (ties retained).
                        axis.step([ordered[0], *ordered], [0., *[(i + 1) / len(ordered) for i in range(len(ordered))]],
                                  where="post", label=label, color=COLORS[width])
                    else:
                        axis.scatter(work, ratios, s=9, alpha=.65, color=COLORS[width],
                                     label=label, linewidths=0, rasterized=False)
                    all_ratios.extend(ratios)
                    all_work.extend(work)
                    panel_counts[str(width)] = {"cases": len(rows), "losses": losses,
                                               "case_ids": [row["case_id"] for row in rows]}
                axis.set_title(f"({chr(97 + index)}) {title}", pad=5)
                axis.set_xscale("log")
                log_ticks(axis, "x")
                if kind == "cdf":
                    axis.set_xlim(min(.9, min(all_ratios) * .88), max(1.1, max(all_ratios) * 1.12))
                    axis.set_ylim(0, 1.03)
                    axis.set_yticks([0, .5, 1])
                    axis.axvline(1, color="#333333", linestyle="--", linewidth=.8, zorder=0)
                    axis.set_xlabel("Fastest control / saturation", labelpad=3)
                    axis.legend(loc="lower right", borderpad=.3, labelspacing=.25,
                                handlelength=1.1, handletextpad=.4, framealpha=.75,
                                title="Slower cases", title_fontsize=8)
                    if index == 0:
                        axis.set_ylabel("Cumulative fraction", labelpad=3)
                else:
                    axis.set_yscale("log")
                    log_ticks(axis, "y")
                    axis.set_xlim(min(all_work) * .93, max(all_work) * 1.15)
                    axis.set_ylim(min(.9, min(all_ratios) * .85), max(1.1, max(all_ratios) * 1.18))
                    axis.axhline(1, color="#333333", linestyle="--", linewidth=.8, zorder=0)
                    axis.set_xlabel("Full scan / saturation visits", labelpad=3)
                    axis.legend(loc="upper left", borderpad=.3, labelspacing=.25,
                                handlelength=.8, handletextpad=.35, framealpha=.65, markerscale=1.2,
                                title="Slower cases", title_fontsize=8)
                    if index == 0:
                        axis.set_ylabel("Full active scan /\nsaturation time", labelpad=2)
                axis.grid(True, which="major", color="#cccccc", linewidth=.45, alpha=.6)
                axis.set_axisbelow(True)
                plotted[kind][study["label"]] = panel_counts
            for suffix in ("pdf", "png", "svg"):
                name = f"saturation-{kind}.{suffix}"
                # No tight bounding-box crop: the exported canvas remains exactly 7.2 x 2.6 inches.
                figure.savefig(directory / name, dpi=300)
                outputs.append(name)
            plt.close(figure)
    return outputs, plotted


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence", type=Path, default=DEFAULT_EVIDENCE)
    parser.add_argument("--paper-directory", type=Path, default=ROOT / "paper")
    args = parser.parse_args()
    evidence_path = args.evidence.resolve()
    paper = args.paper_directory.resolve()
    studies, evidence, auditor, checked, evidence_hash = checked_evidence(evidence_path)
    renderer_hash = sha(__file__)
    table = table_text(studies, evidence_hash, renderer_hash, evidence["auditor_sha256"])
    with tempfile.TemporaryDirectory(prefix="saturation-paper-render-") as temporary:
        staging = Path(temporary)
        generated_figures, plotted = figures(studies, staging)
        table_name = "active_prefix_results_table.tex"
        (staging / table_name).write_text(table)
        require(sha(evidence_path) == evidence_hash and sha(__file__) == renderer_hash
                and sha(AUDITOR) == evidence["auditor_sha256"], "Render source changed during generation")
        require(validate_receipts(evidence, auditor) == checked, "Evidence receipts changed during generation")
        destinations = {table_name: paper / table_name,
                        **{name: paper / "figures" / name for name in generated_figures}}
        output_hashes = {str(destination): sha(staging / name) for name, destination in destinations.items()}
        report = {
            "schema_version": 1, "status": "CHECKED_PRESENTATION_GENERATED",
            "created_utc": datetime.now(timezone.utc).isoformat(),
            "evidence_path": str(evidence_path), "evidence_sha256": evidence_hash,
            "renderer_sha256": renderer_hash, "auditor_sha256": evidence["auditor_sha256"],
            "validation": "All source receipt hashes checked; complete independent raw audit and summary reconstruction rerun; "
                          "stored study objects match reconstructed values exactly apart from relocatable directory paths.",
            "studies": checked, "figure_size_inches": [7.2, 2.6],
            "figure_font_points": {"body": 8.5, "titles": 9, "ticks_and_legend": 8},
            "figure_quantities": {
                "cdf": "Per-case fastest of eight control median times / saturation median time, all widths.",
                "work": "Matched active_full/saturation ablation: summed visited support positions on x; "
                        "median public-call runtime ratio on y. Descriptive association, not a causal timing estimate.",
            },
            "plotted_case_coverage": plotted, "output_sha256": output_hashes,
            "primary_decisions": {study["label"]: study["primary_decision"] for study in studies},
            "scope": "Presentation conversion only; no new timings, no data exclusions, no new decision criterion. "
                     "The retrospective fastest-eight-control oracle uses all eight measured controls per case. "
                     "The generated table contains every comparator at every width in all three studies.",
        }
        for name, destination in destinations.items():
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes((staging / name).read_bytes())
            require(sha(destination) == output_hashes[str(destination)], f"Output write mismatch: {destination}")
        receipt = paper / "active_prefix_results_table.receipt.json"
        receipt.write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")
    print(json.dumps({"table": str(paper / table_name), "figures": generated_figures,
                      "receipt": str(receipt), "primary_decisions": report["primary_decisions"]}, indent=2))


if __name__ == "__main__":
    main()
